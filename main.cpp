#include <string>
#include <vector>

void digit_product() {
    int n = 2345;
    int product = 1;
    while (n > 0) {
        product *= (n % 10);
        n /= 10;
    }
    (void)product;
}

void digit_count() {
    int n = 1234567;
    int digits = 0;
    while (n > 0) { digits += 1; n /= 10; }
    (void)digits;
}

void count_zeros() {
    int n = 102030;
    int zeros = 0;
    while (n > 0) { if (n % 10 == 0) zeros += 1; n /= 10; }
    (void)zeros;
}

void fibonacci_step() {
    int f0 = 0, f1 = 1;
    for (int i = 0; i < 10; ++i) {
        int next = f0 + f1;
        f0 = f1;
        f1 = next;
    }
    (void)f1;
}

extern "C" int bright_harbor();
extern "C" void prime_fjord();
extern "C" void hidden_boulder();
extern "C" void still_prism();
extern "C" void clever_orbit();

int main() {
    digit_product();
    digit_count();
    count_zeros();
    fibonacci_step();
    prime_fjord();
    hidden_boulder();
    still_prism();
    clever_orbit();
    return bright_harbor();
}
